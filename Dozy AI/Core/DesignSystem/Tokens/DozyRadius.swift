import CoreGraphics

enum DozyRadius {
    /// 4 — 작은 배지/태그.
    static let xs: CGFloat = 4
    /// 8 — 인풋, 작은 카드.
    static let sm: CGFloat = 8
    /// 12 — 기본 카드/버튼.
    static let md: CGFloat = 12
    /// 16 — 큰 카드, 시트.
    static let lg: CGFloat = 16
    /// 24 — 모달/바텀시트.
    static let xl: CGFloat = 24
    /// 9999 — pill (완전 원형 처리).
    static let pill: CGFloat = 9999
}
